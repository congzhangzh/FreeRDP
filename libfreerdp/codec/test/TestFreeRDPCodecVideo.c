static size_t frame_size(FREERDP_VIDEO_FORMAT format)
{
	switch (format)
	{
		case FREERDP_VIDEO_FORMAT_YUV420P:
		case FREERDP_VIDEO_FORMAT_NV12:
			return WIDTH * HEIGHT * 3 / 2;
		case FREERDP_VIDEO_FORMAT_YUYV422:
			return WIDTH * HEIGHT * 2;
		case FREERDP_VIDEO_FORMAT_RGB24:
			return WIDTH * HEIGHT * 3;
		case FREERDP_VIDEO_FORMAT_RGB32:
			return WIDTH * HEIGHT * 4;
		default:
			return 0;
	}
}

/* Every conversion that freerdp_video_conversion_supported announces is one the rdpecam client
 * offers to the server (camera_device_main.c getSupportedFormats): it must also convert a frame. */
static BOOL test_announced_conversions_work(void)
{
	const FREERDP_VIDEO_FORMAT formats[] = {
		FREERDP_VIDEO_FORMAT_MJPEG, FREERDP_VIDEO_FORMAT_H264,    FREERDP_VIDEO_FORMAT_YUV420P,
		FREERDP_VIDEO_FORMAT_NV12,  FREERDP_VIDEO_FORMAT_YUYV422, FREERDP_VIDEO_FORMAT_RGB24,
		FREERDP_VIDEO_FORMAT_RGB32,
	};
	BOOL rc = TRUE;
	BYTE* raw = calloc(1, WIDTH * HEIGHT * 4);
	wStream* out = Stream_New(nullptr, 1024);
	if (!raw || !out)
		goto fail;

	for (size_t s = 0; s < ARRAYSIZE(formats); s++)
	{
		for (size_t d = 0; d < ARRAYSIZE(formats); d++)
		{
			const FREERDP_VIDEO_FORMAT src = formats[s];
			const FREERDP_VIDEO_FORMAT dst = formats[d];
			if ((src == dst) || !freerdp_video_conversion_supported(src, dst))
				continue;

			const BYTE* data = raw;
			size_t size = frame_size(src);
			if (src == FREERDP_VIDEO_FORMAT_MJPEG)
			{
				data = test_jpeg;
				size = sizeof(test_jpeg);
			}

			BOOL ok = FALSE;
			FREERDP_VIDEO_CONTEXT* video = freerdp_video_context_new(WIDTH, HEIGHT);
			Stream_ResetPosition(out);
			if (video && freerdp_video_context_reconfigure(video, WIDTH, HEIGHT, 30, 0,
			                                               H264_CAMERA_VIDEO_REAL_TIME))
			{
				/* an encoder may hold the first frame back: give it a few */
				for (size_t i = 0; (i < 8) && (Stream_GetPosition(out) == 0); i++)
				{
					if (!freerdp_video_sample_convert(video, src, data, size, dst, out))
						break;
				}
				ok = Stream_GetPosition(out) > 0;
			}
			freerdp_video_context_free(video);

			(void)printf("%s -> %s: announced, %s\n", freerdp_video_format_string(src),
			             freerdp_video_format_string(dst), ok ? "converts" : "FAILS");
			if (!ok)
				rc = FALSE;
		}
	}

fail:
	Stream_Free(out, TRUE);
	free(raw);
	return rc && out && raw;
}

/* A raw sample comes from the remote side on a camera server: one shorter than a frame of the
 * context's size must be refused, never read past its end. */
static BOOL test_short_sample_refused(void)
{
	if (!freerdp_video_conversion_supported(FREERDP_VIDEO_FORMAT_NV12,
	                                        FREERDP_VIDEO_FORMAT_YUYV422))
		return TRUE;

	const size_t size = frame_size(FREERDP_VIDEO_FORMAT_NV12) - 1;
	BYTE* raw = calloc(1, size);
	wStream* out = Stream_New(nullptr, 1024);
	FREERDP_VIDEO_CONTEXT* video = freerdp_video_context_new(WIDTH, HEIGHT);
	BOOL rc = FALSE;
	if (raw && out && video &&
	    freerdp_video_context_reconfigure(video, WIDTH, HEIGHT, 30, 0, H264_CAMERA_VIDEO_REAL_TIME))
		rc = !freerdp_video_sample_convert(video, FREERDP_VIDEO_FORMAT_NV12, raw, size,
		                                   FREERDP_VIDEO_FORMAT_YUYV422, out);
	(void)printf("NV12 sample of %" PRIuz " bytes for %dx%d: %s\n", size, WIDTH, HEIGHT,
	             rc ? "refused" : "ACCEPTED");
	freerdp_video_context_free(video);
	Stream_Free(out, TRUE);
	free(raw);
	return rc;
}

static BOOL convert_once(FREERDP_VIDEO_CONTEXT* video, UINT32 width, UINT32 height,
                         FREERDP_VIDEO_FORMAT src, const BYTE* data, size_t size,
                         FREERDP_VIDEO_FORMAT dst, wStream* out)
{
	Stream_ResetPosition(out);
	return freerdp_video_context_reconfigure(video, width, height, 30, 0,
	                                         H264_CAMERA_VIDEO_REAL_TIME) &&
	       freerdp_video_sample_convert(video, src, data, size, dst, out) &&
	       (Stream_GetPosition(out) > 0);
}

/* A camera server gets its samples from the remote side: a JPEG of another size than the
 * stream's, and a smaller frame after the stream shrank, must not be read past their end
 * (run under ASan to see it). */
static BOOL test_remote_sizes(void)
{
	BOOL rc = FALSE;
	BYTE* raw = calloc(1, WIDTH * HEIGHT * 4);
	wStream* out = Stream_New(nullptr, 1024);
	FREERDP_VIDEO_CONTEXT* video = freerdp_video_context_new(WIDTH * 2, HEIGHT);
	if (!raw || !out || !video)
		goto fail;

	if (freerdp_video_conversion_supported(FREERDP_VIDEO_FORMAT_MJPEG,
	                                       FREERDP_VIDEO_FORMAT_YUYV422))
	{
		const BOOL ok =
		    convert_once(video, WIDTH * 2, HEIGHT, FREERDP_VIDEO_FORMAT_MJPEG, test_jpeg,
		                 sizeof(test_jpeg), FREERDP_VIDEO_FORMAT_YUYV422, out);
		(void)printf("%dx%d JPEG in a %dx%d stream: %s\n", WIDTH, HEIGHT, WIDTH * 2, HEIGHT,
		             ok ? "ACCEPTED" : "refused");
		if (ok)
			goto fail;
	}

	if (freerdp_video_conversion_supported(FREERDP_VIDEO_FORMAT_NV12, FREERDP_VIDEO_FORMAT_YUYV422))
	{
		const BOOL big =
		    convert_once(video, WIDTH * 2, HEIGHT, FREERDP_VIDEO_FORMAT_NV12, raw,
		                 WIDTH * 2 * HEIGHT * 3 / 2, FREERDP_VIDEO_FORMAT_YUYV422, out);
		const BOOL small =
		    convert_once(video, WIDTH / 2, HEIGHT / 2, FREERDP_VIDEO_FORMAT_NV12, raw,
		                 (WIDTH / 2) * (HEIGHT / 2) * 3 / 2, FREERDP_VIDEO_FORMAT_YUYV422, out);
		const size_t smallSize = Stream_GetPosition(out);
		(void)printf("NV12 %dx%d then %dx%d: %s, %s (%" PRIuz " bytes)\n", WIDTH * 2, HEIGHT,
		             WIDTH / 2, HEIGHT / 2, big ? "converts" : "FAILS",
		             small ? "converts" : "FAILS", smallSize);
		if (!big || !small || (smallSize != (size_t)(WIDTH / 2) * (HEIGHT / 2) * 2))
			goto fail;
	}
	rc = TRUE;

fail:
	freerdp_video_context_free(video);
	Stream_Free(out, TRUE);
	free(raw);
	return rc;
}

int TestFreeRDPCodecVideo(int argc, char* argv[])
{
	WINPR_UNUSED(argc);
	WINPR_UNUSED(argv);

	(void)printf("video conversions available: %s\n", freerdp_video_available() ? "yes" : "no");
	if (!test_announced_conversions_work())
		return -1;
	if (!test_short_sample_refused())
		return -1;
	if (!test_remote_sizes())
		return -1;
	return 0;
}
